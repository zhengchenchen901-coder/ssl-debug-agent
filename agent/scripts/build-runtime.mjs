import { createHash } from "node:crypto";
import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";
import { remoteLogQuery } from "../log-query-remote.js";
import { createRemoteResourceRuntime } from "../remote-resource-runtime.js";
import { remoteResourceProbe } from "../remote-resource-sampler.js";
import { remoteLogJob } from "../log-job-remote.js";
import { buildTerminalAssets } from "./build-terminal-assets.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const agentDir = path.resolve(scriptDir, "..");
const projectRoot = path.resolve(agentDir, "..");
const pluginRoot = path.resolve(projectRoot, "plugins", "remote-debug-agent");
const outputDir = path.resolve(pluginRoot, "runtime", "agent");
const pluginManifestPath = path.resolve(
  pluginRoot,
  ".codex-plugin",
  "plugin.json",
);

const pluginManifest = JSON.parse(
  await fsp.readFile(pluginManifestPath, "utf8"),
);
const agentPackage = JSON.parse(
  await fsp.readFile(path.resolve(agentDir, "package.json"), "utf8"),
);
const pluginBaseVersion = pluginManifest.version.split("+", 1)[0];
if (agentPackage.version !== pluginBaseVersion) {
  throw new Error(
    `version mismatch: agent ${agentPackage.version}, plugin base ${pluginBaseVersion}`,
  );
}

const nativeFallbackPlugin = {
  name: "ssh2-native-fallback",
  setup(buildContext) {
    buildContext.onResolve({ filter: /sshcrypto\.node$/ }, (args) => ({
      path: args.path,
      external: true,
    }));
  },
};

// The local Agent runs Node 22; deployed applications may still use Node 12.
// Serialize a separately transpiled helper rather than the local function body.
const remoteLogRuntime = await transform(`const runRemoteLogQuery = ${remoteLogQuery.toString()};`, {
  target: "node12", platform: "node", format: "cjs", legalComments: "none",
});
const remoteJobRuntime = await transform(`const runRemoteLogJob = ${remoteLogJob.toString()};`, {
  target: "node12", platform: "node", format: "cjs", legalComments: "none",
});
const resourceRuntime = await transform(`const createRemoteResourceRuntime = ${createRemoteResourceRuntime.toString()};`, {
  target: "node12", platform: "node", format: "cjs", legalComments: "none",
});
const resourceProbe = await transform(`const readRemoteResources = ${remoteResourceProbe.toString()};\nconsole.log(JSON.stringify(readRemoteResources()));`, {
  target: "node12", platform: "node", format: "cjs", legalComments: "none",
});
await fsp.writeFile(path.join(agentDir, "remote-resource-runtime-source.js"),
  `// Generated for remote Node 12+.\nexport const REMOTE_RESOURCE_RUNTIME_SOURCE = ${JSON.stringify(resourceRuntime.code)};\nexport const REMOTE_RESOURCE_PROBE_SOURCE = ${JSON.stringify(resourceProbe.code)};\n`, "utf8");
await fsp.writeFile(path.join(agentDir, "log-query-runtime-source.js"),
  `// Generated by scripts/build-runtime.mjs for remote Node 12+ hosts.\nexport const LOG_QUERY_RUNTIME_SOURCE = ${JSON.stringify(remoteLogRuntime.code)};\nexport const LOG_JOB_RUNTIME_SOURCE = ${JSON.stringify(remoteJobRuntime.code)};\n`, "utf8");

async function bundle(entryPoint, outfile) {
  await build({
    entryPoints: [path.resolve(agentDir, entryPoint)],
    outfile: path.resolve(outputDir, outfile),
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node22.18",
    packages: "bundle",
    external: ["cpu-features"],
    plugins: [nativeFallbackPlugin],
    define: {
      "import.meta.url": "undefined",
    },
    minify: false,
    legalComments: "none",
    charset: "utf8",
    logLevel: "info",
  });
}

async function hashFile(filePath) {
  const contents = await fsp.readFile(filePath);
  return createHash("sha256").update(contents).digest("hex");
}

await fsp.rm(outputDir, { recursive: true, force: true });
await fsp.mkdir(outputDir, { recursive: true });

await buildTerminalAssets();
await bundle("server.js", "server.cjs");
await bundle("worker-entry.js", "worker-entry.cjs");
await fsp.cp(path.resolve(agentDir, "public"), path.resolve(outputDir, "public"), {
  recursive: true,
});
await fsp.cp(path.resolve(agentDir, "native"), path.resolve(outputDir, "native"), { recursive: true });

async function listArtifacts(directory, prefix) {
  const result = [];
  for (const entry of (await fsp.readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
    const name = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await listArtifacts(path.join(directory, entry.name), name));
    else result.push(name);
  }
  return result;
}
const artifactFiles = ["server.cjs", "worker-entry.cjs",
  ...await listArtifacts(path.join(outputDir, "public"), "public"),
  ...await listArtifacts(path.join(outputDir, "native"), "native"),
];
const hashes = {};
for (const relativePath of artifactFiles) {
  hashes[relativePath] = await hashFile(path.resolve(outputDir, relativePath));
}

const runtimeHash = createHash("sha256")
  .update(JSON.stringify(hashes))
  .digest("hex");
const manifest = {
  version: 1,
  pluginVersion: pluginManifest.version,
  runtimeId: `${agentPackage.version}:${runtimeHash}`,
  node: agentPackage.engines.node,
  server: "server.cjs",
  worker: "worker-entry.cjs",
  hashes,
};

await fsp.writeFile(
  path.resolve(outputDir, "runtime-manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
  "utf8",
);

if (!fs.existsSync(path.resolve(outputDir, manifest.server))) {
  throw new Error("bundled manager entrypoint was not created");
}
if (!fs.existsSync(path.resolve(outputDir, manifest.worker))) {
  throw new Error("bundled worker entrypoint was not created");
}

console.log(`Built Remote Debug Agent runtime ${manifest.runtimeId}`);
